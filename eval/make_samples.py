"""Generate the two sample reports the deliverable requires.

Deliberately contrasting: one company with a rich public footprint, one with a thin one. Two
happy-path reports would only show that the happy path works. The thin one is the harder deliverable
and the more honest demonstration, because the correct output there is close to nothing.

Reports are generated through the documented run path and written unedited — the build plan forbids
hand-shaping artefacts, and a sample report tidied by hand proves nothing about the system.

    python eval/make_samples.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from ai_prescan import browser, config, graph, render  # noqa: E402

SAMPLES = Path(__file__).resolve().parents[1] / "samples"

TARGETS = [
    ("Personio", "rich-footprint", "personio.md"),
    ("Ballymaloe Foods", "thin-footprint", "ballymaloe-foods.md"),
]


def main() -> int:
    config.preflight(require_live=True)
    browser.install()
    SAMPLES.mkdir(exist_ok=True)

    for company, label, filename in TARGETS:
        print(f"scanning {company} ({label}) …", flush=True)
        report = graph.scan(company, use_fixtures=False)
        text = render.to_markdown(report)
        path = SAMPLES / filename
        path.write_text(
            f"<!-- Generated by `python eval/make_samples.py`. Not hand-edited. -->\n\n{text}"
        )
        print(f"  {len(report.findings)} findings, {report.undetermined_count} undetermined "
              f"-> {path.relative_to(SAMPLES.parent)}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
